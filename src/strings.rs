//! Save URLs interface strings in English, Russian and Ukrainian.
//!
//! The current language lives in a process-wide atomic, because the tray thread and the library
//! store need the strings too, not only the egui window. [`set_lang`] switches it (the window
//! calls it at startup and whenever the user picks another language), [`s`] returns the table.

use crate::i18n::{Lang, Table};
use std::sync::atomic::{AtomicU8, Ordering};

static LANG: AtomicU8 = AtomicU8::new(0);

pub fn set_lang(lang: Lang) {
    LANG.store(lang as u8, Ordering::SeqCst);
}

pub fn lang() -> Lang {
    match LANG.load(Ordering::SeqCst) {
        1 => Lang::Ru,
        2 => Lang::Uk,
        _ => Lang::En,
    }
}

/// Strings for the current language.
pub fn s() -> &'static S {
    TABLE.get(lang())
}

